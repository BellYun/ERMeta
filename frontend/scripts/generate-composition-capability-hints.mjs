import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const frontendDirectory = join(scriptDirectory, "..");
const sourcePath = join(frontendDirectory, "public/l10n/Korean.json");
const outputPath = join(frontendDirectory, "src/generated/compositionCapabilityHints.ts");

const l10n = JSON.parse(await readFile(sourcePath, "utf8"));

const SIGNALS = {
  hardControl: [
    /기절/g,
    /속박/g,
    /공중에 띄/g,
    /넘어뜨/g,
    /넉백/g,
    /밀어냅/g,
    /끌어당/g,
    /도발/g,
    /공포/g,
    /수면/g,
    /침묵/g,
    /무장 해제/g,
  ],
  softControl: [/이동 속도[^.\\n]*(?:감소|느려)/g, /둔화/g],
  persistentZone: [
    /영역을 (?:생성|전개)/g,
    /지대를 (?:생성|만들)/g,
    /장치를 (?:생성|설치)/g,
    /벽을 (?:생성|만들)/g,
    /덫을 (?:설치|생성)/g,
    /유지되는 동안/g,
  ],
  allyProtection: [
    /아군[^.\\n]*(?:보호막|회복|피해를 감소|방어력|이동 속도)/g,
    /주변의 아군[^.\\n]*(?:보호막|회복|피해|방어)/g,
  ],
  projectileDenial: [/투사체[^.\\n]*(?:제거|느려|막)/g],
  mobility: [/돌진/g, /순간 이동/g, /도약/g, /지정한 위치로 이동/g, /대상에게 이동/g],
  untargetable: [/대상 지정 불가/g, /지정할 수 없는 상태/g],
  selfSustain: [/자신의 체력[^.\\n]*회복/g, /체력을 회복/g, /보호막을 획득/g],
  repeatedPressure: [
    /스킬을 재사용/g,
    /일정 시간마다/g,
    /지속적으로/g,
    /기본 공격/g,
    /쿨다운이 감소/g,
  ],
  executePressure: [/잃은 체력/g, /처치하면/g, /처치 시/g],
  visionControl: [/시야를 (?:확보|차단|감소)/g, /은신/g],
};

function countMatches(text, patterns) {
  return patterns.reduce((total, pattern) => total + (text.match(pattern)?.length ?? 0), 0);
}

function score(rawCount, weight = 1) {
  return Math.min(5, rawCount * weight);
}

const characterNames = Object.entries(l10n)
  .filter(([key]) => /^Character\/Name\/\d+$/.test(key))
  .map(([key, name]) => ({ code: Number(key.split("/").at(-1)), name }))
  .filter(({ code }) => code >= 1 && code <= 999)
  .sort((a, b) => a.code - b.code);

const characters = Object.fromEntries(
  characterNames.map(({ code, name }) => {
    const skillPrefix = String(1_000_000 + code * 1_000);
    const descriptions = Object.entries(l10n)
      .filter(([key]) => key.startsWith(`Skill/LobbyDesc/${skillPrefix.slice(0, 4)}`))
      .map(([, description]) => description);
    const uniqueDescriptions = [...new Set(descriptions)];
    const descriptionText = uniqueDescriptions.join("\n");
    const skillNames = [
      ...new Set(
        Object.entries(l10n)
          .filter(([key]) => key.startsWith(`Skill/Group/Name/${skillPrefix.slice(0, 4)}`))
          .map(([, skillName]) => skillName)
      ),
    ];

    const raw = Object.fromEntries(
      Object.entries(SIGNALS).map(([signal, patterns]) => [
        signal,
        countMatches(descriptionText, patterns),
      ])
    );

    return [
      code,
      {
        name,
        skillNames,
        skillCount: uniqueDescriptions.length,
        hints: {
          hardControl: score(raw.hardControl, 2),
          softControl: score(raw.softControl, 1),
          persistentZone: score(raw.persistentZone, 2),
          allyProtection: score(raw.allyProtection, 2),
          projectileDenial: score(raw.projectileDenial, 3),
          mobility: score(raw.mobility, 1),
          untargetable: score(raw.untargetable, 2),
          selfSustain: score(raw.selfSustain, 1),
          repeatedPressure: score(raw.repeatedPressure, 1),
          executePressure: score(raw.executePressure, 2),
          visionControl: score(raw.visionControl, 2),
        },
      },
    ];
  })
);

const prettierConfig = (await resolveConfig(outputPath)) ?? {};
const output = await format(
  `/* eslint-disable */\n// This file is generated by scripts/generate-composition-capability-hints.mjs.\n// Source: official BSER Korean L10N workspace snapshot. Do not edit manually.\n\nexport const COMPOSITION_CAPABILITY_HINTS = ${JSON.stringify(characters, null, 2)} as const;\n`,
  { ...prettierConfig, filepath: outputPath }
);

await writeFile(outputPath, output);
process.stdout.write(
  `[composition-capability-hints] ${Object.keys(characters).length} characters -> ${outputPath}\n`
);
