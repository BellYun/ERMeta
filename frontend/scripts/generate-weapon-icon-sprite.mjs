import { createHash } from "node:crypto";
import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const frontendRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(frontendRoot, "public", "weapon-icons");
const outputDir = path.join(frontendRoot, "public", "sprites");
const generatedModulePath = path.join(frontendRoot, "src", "generated", "weaponIconSprite.ts");

const CELL_SIZE = 32;
const COLUMNS = 6;

const sourceNames = (await readdir(sourceDir))
  .filter((name) => /^\d+\.png$/.test(name))
  .sort((a, b) => Number.parseInt(a, 10) - Number.parseInt(b, 10));
const codes = sourceNames.map((name) => Number.parseInt(name, 10));
const rows = Math.ceil(sourceNames.length / COLUMNS);

const layers = await Promise.all(
  sourceNames.map(async (name, index) => ({
    input: await sharp(path.join(sourceDir, name))
      .resize(CELL_SIZE, CELL_SIZE, { fit: "contain" })
      .png()
      .toBuffer(),
    left: (index % COLUMNS) * CELL_SIZE,
    top: Math.floor(index / COLUMNS) * CELL_SIZE,
  }))
);

const atlas = await sharp({
  create: {
    width: COLUMNS * CELL_SIZE,
    height: rows * CELL_SIZE,
    channels: 4,
    background: { r: 0, g: 0, b: 0, alpha: 0 },
  },
})
  .composite(layers)
  .webp({ lossless: true })
  .toBuffer();

const hash = createHash("sha256").update(atlas).digest("hex").slice(0, 12);
const filename = `weapon-icons.${hash}.webp`;

await mkdir(outputDir, { recursive: true });
await mkdir(path.dirname(generatedModulePath), { recursive: true });
await writeFile(path.join(outputDir, filename), atlas);

const indexEntries = codes.map((code, index) => `  ${code}: ${index},`).join("\n");
const generatedModule = `/* This file is generated by scripts/generate-weapon-icon-sprite.mjs. */

export const WEAPON_ICON_SPRITE_URL = "/sprites/${filename}";
export const WEAPON_ICON_SPRITE_CELL_SIZE = ${CELL_SIZE};
export const WEAPON_ICON_SPRITE_COLUMNS = ${COLUMNS};
export const WEAPON_ICON_SPRITE_ROWS = ${rows};

const WEAPON_ICON_INDEX_BY_CODE: Readonly<Record<number, number>> = {
${indexEntries}
};

export function getWeaponIconSpritePosition(
  code: number
): { column: number; row: number } | null {
  const index = WEAPON_ICON_INDEX_BY_CODE[code];
  if (index == null) return null;

  return {
    column: index % WEAPON_ICON_SPRITE_COLUMNS,
    row: Math.floor(index / WEAPON_ICON_SPRITE_COLUMNS),
  };
}
`;

await writeFile(generatedModulePath, generatedModule);

process.stdout.write(
  JSON.stringify(
    {
      output: `/sprites/${filename}`,
      bytes: atlas.byteLength,
      icons: codes.length,
      width: COLUMNS * CELL_SIZE,
      height: rows * CELL_SIZE,
    },
    null,
    2
  ) + "\n"
);
