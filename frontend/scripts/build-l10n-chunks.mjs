#!/usr/bin/env node
/* eslint-disable no-console */

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const FRONTEND_DIR = join(__dirname, "..");
const SOURCE_DIR = join(FRONTEND_DIR, "public/l10n");
const OUTPUT_DIR = join(SOURCE_DIR, "chunks");
const MANIFEST_PATH = join(FRONTEND_DIR, "src/generated/l10nManifest.ts");

const LANGUAGES = ["Korean", "English", "Japanese"];
const NAMESPACES = {
  core: ["Character/Name/", "WeaponType/", "Trait/Name/"],
  "item-names": ["Item/Name/"],
};

function buildChunk(source, prefixes) {
  return Object.fromEntries(
    Object.entries(source)
      .filter(([key]) => prefixes.some((prefix) => key.startsWith(prefix)))
      .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
  );
}

function getContentHash(content) {
  return createHash("sha256").update(content).digest("hex").slice(0, 12);
}

rmSync(OUTPUT_DIR, { recursive: true, force: true });
mkdirSync(OUTPUT_DIR, { recursive: true });

const manifest = {};

for (const language of LANGUAGES) {
  const sourcePath = join(SOURCE_DIR, `${language}.json`);
  const source = JSON.parse(readFileSync(sourcePath, "utf8"));
  const languageOutputDir = join(OUTPUT_DIR, language);

  mkdirSync(languageOutputDir, { recursive: true });
  manifest[language] = {};

  for (const [namespace, prefixes] of Object.entries(NAMESPACES)) {
    const chunk = buildChunk(source, prefixes);
    const content = JSON.stringify(chunk);
    const hash = getContentHash(content);
    const filename = `${namespace}.${hash}.json`;

    writeFileSync(join(languageOutputDir, filename), content, "utf8");
    manifest[language][namespace] = `/l10n/chunks/${language}/${filename}`;

    console.log(
      `[build-l10n-chunks] ${language}/${namespace}: ${Object.keys(chunk).length} keys -> ${filename}`
    );
  }
}

const manifestSource = `// This file is generated by scripts/build-l10n-chunks.mjs.\n// Do not edit manually.\n\nexport const L10N_CHUNK_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n\nexport type L10nNamespace = keyof (typeof L10N_CHUNK_MANIFEST)["Korean"];\n`;

mkdirSync(dirname(MANIFEST_PATH), { recursive: true });
writeFileSync(MANIFEST_PATH, manifestSource, "utf8");

console.log(`[build-l10n-chunks] manifest -> ${MANIFEST_PATH}`);
