#!/usr/bin/env node
/* eslint-disable no-console */

import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const outputPath = join(scriptDirectory, "../src/generated/characterControlDifficulty.ts");

const WEAPON_TYPE_CODES = {
  Glove: 1,
  Tonfa: 2,
  Bat: 3,
  Whip: 4,
  HighAngleFire: 5,
  DirectFire: 6,
  Bow: 7,
  CrossBow: 8,
  Pistol: 9,
  AssaultRifle: 10,
  SniperRifle: 11,
  Hammer: 13,
  Axe: 14,
  OneHandSword: 15,
  TwoHandSword: 16,
  Polearm: 17,
  DualSword: 18,
  Spear: 19,
  Nunchaku: 20,
  Rapier: 21,
  Guitar: 22,
  Camera: 23,
  Arcana: 24,
  VFArm: 25,
};

const apiKey = process.env.BSER_API_KEY;
if (!apiKey) throw new Error("BSER_API_KEY 환경변수가 필요합니다.");

async function fetchTable(path) {
  const response = await fetch(`https://open-api.bser.io${path}`, {
    headers: { accept: "application/json", "x-api-key": apiKey },
  });
  if (!response.ok) throw new Error(`${path}: ${response.status}`);
  return response.json();
}

const [attributesResponse, hashResponse] = await Promise.all([
  fetchTable("/v2/data/CharacterAttributes"),
  fetchTable("/v2/data/hash"),
]);
const rows = attributesResponse.data ?? [];
const tableHash = hashResponse.data?.CharacterAttributes;
const byProfile = {};
const ratingsByCharacter = new Map();

for (const row of rows) {
  const weaponCode = WEAPON_TYPE_CODES[row.mastery];
  if (!weaponCode) throw new Error(`알 수 없는 무기 타입: ${row.mastery}`);
  if (
    !Number.isInteger(row.controlDifficulty) ||
    row.controlDifficulty < 1 ||
    row.controlDifficulty > 5
  ) {
    throw new Error(`잘못된 조작 난이도: ${JSON.stringify(row)}`);
  }
  byProfile[`${row.characterCode}:${weaponCode}`] = row.controlDifficulty;
  const ratings = ratingsByCharacter.get(row.characterCode) ?? new Set();
  ratings.add(row.controlDifficulty);
  ratingsByCharacter.set(row.characterCode, ratings);
}

const byCharacter = {};
for (const [characterCode, ratings] of ratingsByCharacter) {
  if (ratings.size !== 1) {
    throw new Error(`무기별 조작 난이도가 다른 실험체: ${characterCode}`);
  }
  byCharacter[characterCode] = [...ratings][0];
}

const source = `// This file is generated by scripts/generate-character-control-difficulty.mjs.
// Source: Nimble Neuron Open API /v2/data/CharacterAttributes. Do not edit manually.

export const CHARACTER_ATTRIBUTES_TABLE_HASH = ${JSON.stringify(tableHash)} as const;

export const OFFICIAL_CONTROL_DIFFICULTY_BY_PROFILE = ${JSON.stringify(byProfile, null, 2)} as const;

export const OFFICIAL_CONTROL_DIFFICULTY_BY_CHARACTER = ${JSON.stringify(byCharacter, null, 2)} as const;
`;
const prettierConfig = (await resolveConfig(outputPath)) ?? {};
await writeFile(outputPath, await format(source, { ...prettierConfig, filepath: outputPath }));
console.log(
  `[character-control-difficulty] ${Object.keys(byProfile).length} profiles / ${Object.keys(byCharacter).length} characters -> ${outputPath}`
);
